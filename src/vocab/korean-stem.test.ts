import { describe, expect, it } from 'vitest';
import { sameKoreanPredicate } from './korean-stem';

const plain = (text: string) => text.replace(/\s/g, '');

describe('sameKoreanPredicate', () => {
  it.each([
    ['재미있는', '재미있다'], ['재밌는', '재미있다'], ['재밌어요', '재미있다'], ['재미있었나요', '재미있다'], ['재미있더라고요', '재미있다'],
    ['큰', '크다'], ['커요', '크다'], ['컸어요', '크다'], ['단', '달다'], ['아름다운', '아름답다'], ['무거워요', '무겁다'],
    ['바빠요', '바쁘다'], ['빨라요', '빠르다'], ['친절한', '친절하다'], ['갑니다', '가다'], ['사는', '살다'], ['긴', '길다'],
    ['파란', '파랗다'], ['걸어요', '걷다'], ['걸었어요', '걷다'], ['들으면', '듣다'], ['물어요', '묻다'], ['나아요', '낫다'], ['나았어요', '낫다'], ['지어요', '짓다'], ['가세요', '가다'], ['드세요', '들다'], ['했어요', '하다'], ['따뜻했더라면', '따뜻하다'], ['자다', '잡니다'], ['살고 있어요', '살고 있습니다'],
  ])('%s is a form of %s', (typed, meaning) => {
    expect(sameKoreanPredicate(plain(typed), plain(meaning))).toBe(true);
  });

  it.each([
    ['즐거운', '재미있다'], ['재미없다', '재미있다'], ['재미', '재미있다'], ['달', '달다'], ['키', '크다'], ['크기', '크다'],
    ['사다', '살다'], ['싸다', '쓰다'], ['좋아하다', '좋다'], ['어려운', '어리다'], ['작년', '작다'], ['가을', '가다'], ['가지', '갑니다'],
    ['하나', '합니다'], ['보고서', '봅니다'], ['보안', '봅니다'], ['마을', '마십니다'], ['자세', '잡니다'], ['저울', '접습니다'],
    ['단', '닿다'], ['기분', '기부'], ['자세', '잡니다'], ['걸고', '걷다'], ['나고', '낫다'], ['물', '묻다'], ['달립니다', '걸립니다'], ['깨끗하게', '깨끗하다'],
  ])('%s is not %s', (typed, meaning) => {
    expect(sameKoreanPredicate(plain(typed), plain(meaning))).toBe(false);
  });
});
